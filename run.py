"""Build the database, run governance, write the catalog, lineage and report."""
import pandas as pd

from govern.data import PLANTED, build, load_sqlite
from govern import governance as G

con = load_sqlite(build())
G.run_sql_file(con)
rules = G.run_rules(con)
cat = G.build_catalog(con)
ready = G.ai_readiness(con, cat, rules)
metrics = G.compute_metrics(con)
sources, edges = G.lineage()
exc = pd.read_sql("SELECT reason, COUNT(*) AS records FROM exceptions GROUP BY reason ORDER BY records DESC", con)

raw_rows = G.q1(con, "SELECT COUNT(*) FROM raw_orders")
mart_rows = G.q1(con, "SELECT COUNT(*) FROM fct_orders")
by_layer = cat.groupby("layer").agg(columns=("column", "size"), documented=("documented", "mean"),
                                    classified=("classified", "mean"))
rl = rules.groupby("layer").agg(rules=("rule_id", "size"), failed=("status", lambda s: (s == "FAIL").sum()),
                               failing_rows=("failing_rows", "sum"))
metric_lineage = {m: sorted(G.upstream_sources(f"metric:{m}", edges, sources)) for m in metrics.name}

summary = {
    "Tables cataloged": cat.table.nunique(),
    "Columns cataloged": len(cat),
    "Catalog coverage, raw (definition + owner)": by_layer.loc["raw", "documented"],
    "Catalog coverage, mart": by_layer.loc["mart", "documented"],
    "Sensitivity classified, raw": by_layer.loc["raw", "classified"],
    "PII columns tagged": int((cat.sensitivity == "PII").sum()),
    "Data quality rules": len(rules),
    "Raw rules failing / failing rows": f"{rl.loc['raw', 'failed']} / {rl.loc['raw', 'failing_rows']}",
    "Mart rules failing / failing rows": f"{rl.loc['mart', 'failed']} / {rl.loc['mart', 'failing_rows']}",
    "Raw order lines -> certified order lines": f"{raw_rows:,} -> {mart_rows:,}",
    "Records routed to exceptions queue": int(exc.records.sum()),
    "Duplicate accounts merged": G.q1(con, "SELECT COUNT(*) FROM account_merge_map WHERE account_id <> survivor_id"),
    "Lineage edges documented": len(edges),
    "Governed metrics (traced to source)": f"{len(metrics)} ({sum(bool(v) for v in metric_lineage.values())} traced)",
    "Tables AI-ready (certified)": f"{(ready.tier == 'AI-ready (certified)').sum()} of {len(ready)}",
}
for k, v in summary.items():
    print(f"{k:45s} {v:.1%}" if isinstance(v, float) else f"{k:45s} {v}")
print(rules[["rule_id", "dimension", "failing_rows", "status"]].to_string(index=False))
print(ready[["table", "score", "documentation", "validity", "tier"]].round(3).to_string(index=False))
print(metrics[["name", "value"]].to_string(index=False)); print(exc.to_string(index=False))
print("planted:", PLANTED)

with pd.ExcelWriter("governance_report.xlsx") as w:
    pd.Series(summary, name="value").astype(str).to_frame().to_excel(w, sheet_name="Summary")
    cat.to_excel(w, sheet_name="Data Catalog", index=False)
    rules.to_excel(w, sheet_name="Quality Rules", index=False)
    ready.to_excel(w, sheet_name="AI Readiness", index=False)
    metrics.to_excel(w, sheet_name="Governed Metrics", index=False)
    pd.DataFrame(edges, columns=["upstream", "downstream"]).to_excel(w, sheet_name="Lineage", index=False)
    exc.to_excel(w, sheet_name="Exceptions", index=False)

# human-readable catalog and lineage docs
md = ["# Data Catalog", "", "Generated by `run.py` from `config/catalog.yaml` plus automatic profiling.", ""]
for t, g in cat.groupby("table", sort=False):
    meta = G.read_yaml("catalog.yaml").get(t, {})
    md += [f"## {t}", "", f"**Owner:** {meta.get('owner')} · **Steward:** {meta.get('steward')} · "
           f"**Source:** {meta.get('source')} · **Rows:** {int(g.rows.iloc[0]):,}", "",
           meta.get("description", ""), "",
           "| Column | Type | Null % | Distinct | Sensitivity | Definition |", "|---|---|---|---|---|---|"]
    for r in g.itertuples():
        md.append(f"| {r.column}{' 🔑' if r.is_primary_key else ''} | {r.data_type} | {r.null_pct:.1%} | "
                  f"{r.distinct:,} | {r.sensitivity or '⚠️ unclassified'} | {r.definition or '⚠️ undocumented'} |")
    md.append("")
open("docs/data_catalog.md", "w").write("\n".join(md))
open("docs/lineage.md", "w").write("# Lineage\n\n```mermaid\n" + G.lineage_mermaid(edges) + "\n```\n\n"
                                   + "\n".join(f"- **{m}** ← {', '.join(v)}" for m, v in metric_lineage.items()) + "\n")
